#!/usr/bin/env python3
"""Capture the SM64DS ARM9 runtime-RAM image and export its bank config.

The game's ARM9 program copies code out of the static closure at runtime:
the ITCM-resident fast paths (0x01FF8188..), overlays loaded over and past
the static arm9.bin image (0x0200Fxxx, 0x02043xxx, 0x020AAxxx, 0x0232xxxx,
0x023FEE00), all interpreted tier-3 until promoted. This tool is the ARM9
flavor of tools/capture_arm7_ram_bank.py and follows the firmware ARM9
bank model (ndsrecomp tools/capture_firmware_images.py):

  1. drives a native debug server (started with
     `--serve --rom <SM64DS.nds> --discover-static-misses`) through the
     deterministic boot->title->attract navigation and stops at a fixed
     insn9 ordinal inside the byte-locked G3 window;
  2. captures ITCM + main RAM as one contiguous composite source image
     (load address 0x01FF8000: the 32 KiB ITCM high mirror immediately
     precedes main RAM, exactly like the fw_arm9_* banks — no code_copy
     row needed for ITCM);
  3. merges the observed ARM9 tier-3 coverage into the committed
     config/sm64ds_arm9_ram.toml (monotonic: existing entries are kept).

The captured image stays git-ignored under generated/capture; runtime
dispatch validates every generated function against the live guest bytes
(--validate-live-bytes), so a bank row only fires once the guest's own
boot has produced identical code at that address.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "ndsrecomp" / "oracle"))

from _client import DebugClient  # noqa: E402

# Stop inside the proven G3 byte-lock window (boot->title->attract is locked
# vs ndsref through insn9=700M), late enough that the title/attract overlays
# and ITCM-resident code are fully resident and exercised.
CAPTURE_INSN9 = 700_000_000

ITCM_BASE = 0x01FF8000              # ARM9 ITCM high mirror (32 KiB) ...
MAINRAM_BASE = 0x02000000           # ... immediately followed by main RAM
MAINRAM_END = 0x02400000
MAINRAM_MIRROR_END = 0x03000000     # 4 MiB image mirrored at 0x02400000 steps
IMAGE_SIZE = 0x00408000             # composite: ITCM 32 KiB + main RAM 4 MiB

ENTRY_RE = re.compile(
    r"\[\[entry_point\]\]\s*\n"
    r"addr\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*\n"
    r"mode\s*=\s*\"(arm|thumb)\"",
    re.MULTILINE,
)


def existing_entries(path: Path) -> set[tuple[int, str]]:
    if not path.exists():
        return set()
    return {(int(addr, 0), mode)
            for addr, mode in ENTRY_RE.findall(path.read_text())}


def accept(pc: int) -> bool:
    # ITCM high mirror + main RAM including its architectural mirrors. The
    # static sm64ds_arm9 closure (0x02004000..0x020A0F78) is NOT excluded:
    # unlike the ARM7 payload bank the static ARM9 bank is content-validated,
    # so a tier-3 hit inside its range means the guest overwrote that code
    # (overlay) or entered mid-function — both are exactly what this bank
    # promotes, and same-address rows disambiguate by live bytes.
    if ITCM_BASE <= pc < MAINRAM_BASE:
        return True
    return MAINRAM_BASE <= pc < MAINRAM_MIRROR_END


def nav_sm64ds_title(client: DebugClient) -> None:
    """Reset + the deterministic SM64DS boot touches (mirrors
    oracle/probe_gx_state.py nav_sm64ds_title, single-server)."""
    client.cmd("reset")
    client.cmd("run_to_event", event="vblank9", count=100, stall=300_000)
    client.cmd("touch", x=128, y=48, down=True)
    client.cmd("run_to_event", event="vblank9", count=102, stall=300_000)
    client.cmd("touch", x=128, y=48, down=False)
    client.cmd("run_to_event", event="vblank9", count=900, stall=300_000)
    client.cmd("touch", x=128, y=120, down=True)
    client.cmd("run_to_event", event="vblank9", count=930, stall=300_000)
    client.cmd("touch", x=128, y=120, down=False)


def render_config(sha1: str, entry_pc: int, entry_mode: str,
                  entries: set[tuple[int, str]]) -> str:
    lines = [
        "# AUTO-GENERATED by tools/capture_arm9_ram_bank.py; committed.",
        "# Source image is the guest-produced runtime RAM capture",
        "# (generated/capture/sm64ds_arm9_ram.bin, git-ignored); runtime",
        "# dispatch validates every generated function against the current",
        "# live guest bytes before entering it.",
        "",
        "[program]",
        'name         = "Super Mario 64 DS (Europe) ARM9 runtime RAM"',
        'id           = "sm64ds_arm9_ram"',
        'cpu          = "arm9"',
        'isa          = "armv5te"',
        f"load_address = 0x{ITCM_BASE:08X}",
        f"size         = 0x{IMAGE_SIZE:08X}",
        f"entry_pc     = 0x{entry_pc:08X}",
        "",
        "[identity]",
        f'sha1 = "{sha1}"',
        "",
    ]
    # Main-RAM mirror aliases: the 4 MiB image repeats at 0x02400000 steps.
    # Inert unless an entry point lands in a mirror, but complete either way.
    for mirror in range(MAINRAM_END, MAINRAM_MIRROR_END, 0x00400000):
        lines += [
            "[[code_copy]]",
            f"runtime_start = 0x{mirror:08X}",
            f"source_start  = 0x{MAINRAM_BASE:08X}",
            f"size          = 0x{MAINRAM_END - MAINRAM_BASE:08X}",
            'name          = "main RAM mirror alias"',
            "",
        ]
    entries = set(entries)
    entries.add((entry_pc, entry_mode))
    for addr, mode in sorted(entries):
        lines += [
            "[[entry_point]]",
            f"addr = 0x{addr:08X}",
            f'mode = "{mode}"',
            'kind = "runtime_observed"',
            "",
        ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=19842)
    parser.add_argument("--timeout", type=float, default=1800.0)
    parser.add_argument("--insn9", type=int, default=CAPTURE_INSN9)
    parser.add_argument("--out", type=Path,
                        default=REPO / "generated" / "capture")
    parser.add_argument("--config", type=Path,
                        default=REPO / "config" / "sm64ds_arm9_ram.toml")
    parser.add_argument("--skip-nav", action="store_true",
                        help="server is already navigated + stopped; only "
                             "pull coverage and capture")
    args = parser.parse_args()

    client = DebugClient(port=args.port, timeout=args.timeout)
    try:
        if not args.skip_nav:
            nav_sm64ds_title(client)
            reached = client.cmd("run_to_event", event="insn9",
                                 count=args.insn9)
            if not reached.get("reached"):
                raise SystemExit(f"failed to reach insn9={args.insn9}: "
                                 f"{reached}")

        summary = client.cmd("static_coverage")
        coverage = client.cmd("tier3_coverage", max=262144)["entries"]

        itcm = client.read_region("itcm")
        mainram = client.read_region("mainram")
    finally:
        client.close()

    image = itcm + mainram
    if len(image) != IMAGE_SIZE:
        raise SystemExit(f"unexpected composite size 0x{len(image):X} "
                         f"(want 0x{IMAGE_SIZE:X})")
    sha1 = hashlib.sha1(image).hexdigest()

    args.out.mkdir(parents=True, exist_ok=True)
    bin_path = args.out / "sm64ds_arm9_ram.bin"
    bin_path.write_bytes(image)

    observed = [e for e in coverage if e["cpu"] == 9 and accept(e["pc"])]
    roots = [e for e in observed if e["kind"] == 1]
    if not roots:
        raise SystemExit("no ARM9 tier-3 roots observed — was the server "
                         "started with --discover-static-misses?")
    entry = min(roots, key=lambda e: e["pc"])

    entries = existing_entries(args.config)
    before = len(entries)
    entries.update((e["pc"], "thumb" if e["thumb"] else "arm")
                   for e in observed)

    args.config.parent.mkdir(parents=True, exist_ok=True)
    args.config.write_text(
        render_config(sha1, entry["pc"],
                      "thumb" if entry["thumb"] else "arm", entries),
        encoding="utf-8", newline="\n")

    (args.out / "sm64ds_arm9_ram_coverage.json").write_text(
        json.dumps({"static_coverage": summary, "observed": observed},
                   indent=1), encoding="utf-8")

    print(json.dumps({
        "image": str(bin_path),
        "sha1": sha1,
        "insn9": args.insn9,
        "static_coverage": summary,
        "observed_arm9": len(observed),
        "entries_before": before,
        "entries_after": len(entries),
        "entry_pc": f"0x{entry['pc']:08X}",
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
