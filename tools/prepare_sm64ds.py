#!/usr/bin/env python3
"""Prepare ignored SM64DS EU code images and ndsrecomp configs.

The ROM and every derived binary/config remain under generated/, which is
Git-ignored.  Function identities and exact boundaries come from the pinned
tangosdev/sm64ds-decomp checkout; no decompiled source or Nintendo asset is
copied into this repository.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re

try:
    import ndspy.codeCompression as code_compression
    import ndspy.rom
except ImportError as exc:
    raise SystemExit(
        "ndspy is required; run this with the pinned decomp checkout's "
        ".venv Python or install ndspy"
    ) from exc


EXPECTED_ROM_SHA1 = "1367529f2cb23e76ef295cb1727333ae8f0a6cd7"
EXPECTED_GAME_CODE = b"ASMP"
EXPECTED_REVISION = 0
FUNCTION_RE = re.compile(
    r"^(?P<name>.+?) kind:function\((?P<mode>arm|thumb),size=0x"
    r"(?P<size>[0-9a-fA-F]+)\) addr:0x(?P<addr>[0-9a-fA-F]+)$"
)
SECTION_RE = re.compile(
    r"^\s*\.\S+\s+start:0x(?P<start>[0-9a-fA-F]+)\s+"
    r"end:0x(?P<end>[0-9a-fA-F]+)\s+kind:(?P<kind>\w+)"
)


def sha1(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def parse_functions(path: pathlib.Path, start: int, end: int) -> list[dict[str, object]]:
    functions: list[dict[str, object]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = FUNCTION_RE.match(line)
        if not match:
            continue
        addr = int(match.group("addr"), 16)
        size = int(match.group("size"), 16)
        if start <= addr and addr + size <= end:
            functions.append(
                {
                    "addr": addr,
                    "size": size,
                    "mode": match.group("mode"),
                    "name": match.group("name"),
                }
            )
    functions.sort(key=lambda item: (int(item["addr"]), str(item["mode"])))
    return functions


def parse_data_ranges(path: pathlib.Path, start: int, end: int) -> list[tuple[int, int, str]]:
    ranges: list[tuple[int, int, str]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = SECTION_RE.match(line)
        if not match or match.group("kind") == "code":
            continue
        range_start = max(start, int(match.group("start"), 16))
        range_end = min(end, int(match.group("end"), 16))
        if range_start < range_end:
            ranges.append((range_start, range_end, f"decomp {match.group('kind')} section"))
    return ranges


def write_config(
    path: pathlib.Path,
    *,
    name: str,
    program_id: str,
    load_address: int,
    entry_pc: int,
    binary: bytes,
    functions: list[dict[str, object]],
    data_ranges: list[tuple[int, int, str]],
) -> None:
    lines = [
        "# AUTO-GENERATED by tools/prepare_sm64ds.py; do not commit.",
        "[program]",
        f"name = {toml_string(name)}",
        f"id = {toml_string(program_id)}",
        f"load_address = 0x{load_address:08x}",
        f"size = 0x{len(binary):08x}",
        f"entry_pc = 0x{entry_pc:08x}",
        f"authoritative_entry_points = {'true' if functions and all(int(item['size']) > 0 for item in functions) else 'false'}",
        "",
        "[identity]",
        f"sha1 = {toml_string(sha1(binary))}",
        "",
    ]
    for function in functions:
        lines.extend(
            [
                "[[entry_point]]",
                f"addr = 0x{int(function['addr']):08x}",
                f"size = 0x{int(function['size']):x}",
                f"mode = {toml_string(str(function['mode']))}",
                f"name = {toml_string(str(function['name']))}",
                "",
            ]
        )
    for range_start, range_end, note in data_ranges:
        lines.extend(
            [
                "[[data_range]]",
                f"start = 0x{range_start:08x}",
                f"end = 0x{range_end:08x}",
                f"note = {toml_string(note)}",
                "",
            ]
        )
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom", type=pathlib.Path, required=True)
    parser.add_argument("--decomp", type=pathlib.Path, required=True)
    parser.add_argument("--out", type=pathlib.Path, required=True)
    args = parser.parse_args()

    rom_bytes = args.rom.read_bytes()
    digest = sha1(rom_bytes)
    if digest != EXPECTED_ROM_SHA1:
        raise SystemExit(f"ROM SHA-1 mismatch: got {digest}, expected {EXPECTED_ROM_SHA1}")

    rom = ndspy.rom.NintendoDSRom(rom_bytes)
    if bytes(rom.idCode) != EXPECTED_GAME_CODE or rom_bytes[0x1E] != EXPECTED_REVISION:
        raise SystemExit(
            f"ROM identity mismatch: code={bytes(rom.idCode)!r} revision={rom_bytes[0x1E]}"
        )

    arm9 = code_compression.decompress(bytes(rom.arm9))
    if len(arm9) < len(rom.arm9):
        arm9 = bytes(rom.arm9)
    arm7 = bytes(rom.arm7)

    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    (out / "arm9.bin").write_bytes(arm9)
    (out / "arm7.bin").write_bytes(arm7)

    config_dir = args.decomp / "config" / "arm9"
    arm9_start = int(rom.arm9RamAddress)
    arm9_end = arm9_start + len(arm9)
    functions = parse_functions(config_dir / "symbols.txt", arm9_start, arm9_end)
    data_ranges = parse_data_ranges(config_dir / "delinks.txt", arm9_start, arm9_end)
    if not any(int(item["addr"]) == int(rom.arm9EntryAddress) for item in functions):
        raise SystemExit("decomp metadata does not contain the ROM's ARM9 entry point")

    write_config(
        out / "arm9.toml",
        name="Super Mario 64 DS (Europe) ARM9 main",
        program_id="sm64ds_eu_arm9",
        load_address=arm9_start,
        entry_pc=int(rom.arm9EntryAddress),
        binary=arm9,
        functions=functions,
        data_ranges=data_ranges,
    )
    write_config(
        out / "arm7.toml",
        name="Super Mario 64 DS (Europe) ARM7",
        program_id="sm64ds_eu_arm7",
        load_address=int(rom.arm7RamAddress),
        entry_pc=int(rom.arm7EntryAddress),
        binary=arm7,
        functions=[
            {
                "addr": int(rom.arm7EntryAddress),
                "size": 0,
                "mode": "arm",
                "name": "arm7_entry",
            }
        ],
        data_ranges=[],
    )

    print(f"ROM verified: ASMP revision 0, SHA-1 {digest}")
    print(f"ARM9: {len(arm9):,} bytes, {len(functions):,} exact function boundaries")
    print(f"ARM7: {len(arm7):,} bytes, entry discovery only")
    print(f"Prepared ignored inputs under {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
